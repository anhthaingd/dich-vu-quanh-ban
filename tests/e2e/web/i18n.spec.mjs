import { test, expect } from './fixtures.mjs';
test('language changes keep form/session/category, translate errors and persist only the locale on reload', async ({ page, environment }) => {
  await page.goto(environment.webUrl);
  await page.getByRole('button', { name: 'Tài khoản', exact: true }).click();
  await page.getByRole('button', { name: 'Chưa có tài khoản? Đăng ký' }).click();
  await page.getByLabel('Tên hiển thị', { exact: true }).fill('Người thử đa ngôn ngữ');
  await page.getByLabel('Email', { exact: true }).fill('locale@example.test');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('locale-test-only-password');
  await page.getByRole('button', { name: '日本語', exact: true }).click();
  await expect(page.getByLabel('パスワード', { exact: true })).toHaveValue('locale-test-only-password');
  await expect(page.getByLabel('表示名', { exact: true })).toHaveValue('Người thử đa ngôn ngữ');
  await expect(page.locator('html')).toHaveAttribute('lang', 'ja');
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('button', { name: 'Sign up', exact: true }).click();
  await expect(page.getByText('Email not verified', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '日本語', exact: true }).click();
  await expect(page.getByText('メールアドレスは未確認です', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'ログアウト', exact: true }).click();
  await page.getByRole('button', { name: 'アカウントをお持ちですか？ログイン', exact: true }).click();
  await page.getByLabel('パスワード', { exact: true }).fill('wrong-test-password');
  await page.getByRole('button', { name: 'ログイン', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('認証できません');
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Unable to authenticate');
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('button', { name: 'Điện nước', exact: true }).click();
  await page.getByRole('button', { name: '日本語', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Điện nước', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Dịch vụ điện nước', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Dịch vụ điện nước', exact: true }).getByText('サービスを見る →', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'どんなサービスをお探しですか？' })).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('lang', 'ja');
  expect(await page.evaluate(() => ({ ...globalThis.localStorage }))).toEqual({ 'dvqb.locale.v1': 'ja' });
  const horizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(horizontalOverflow).toBe(false);
});
